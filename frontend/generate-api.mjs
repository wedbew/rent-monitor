// `pnpm generate:api` writes the generated types; `pnpm check:api` (--check) fails when the committed files differ.
// Inputs: docs/openapi.json (operations, request/response shapes, problems) and docs/deal-analysis.schema.json (the
// report in AuditOut.result, which OpenAPI keeps opaque on purpose). CI never rewrites the baseline.
import { readFileSync, writeFileSync } from "node:fs";

import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const check = process.argv.includes("--check");
const root = new URL("../", import.meta.url);

const BANNER = "/* eslint-disable */\n// Generated by `pnpm generate:api`. Do not edit.\n";

const api = astToString(await openapiTS(new URL("docs/openapi.json", root)));
const reportSchema = JSON.parse(readFileSync(new URL("docs/deal-analysis.schema.json", root), "utf8"));
const report = await compile(reportSchema, "DealAnalysis", {
  bannerComment: BANNER,
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
});

// The same schema as data, for the runtime check of `AuditOut.result` (api/schema-check.ts). Only keywords that
// constrain a value are kept; titles, descriptions and defaults are documentation.
const DOC_KEYWORDS = new Set(["title", "description", "default", "$id", "$schema", "x-schema-version"]);
const strip = (node) =>
  Array.isArray(node)
    ? node.map(strip)
    : node !== null && typeof node === "object"
      ? Object.fromEntries(
          Object.entries(node)
            .filter(([key]) => !DOC_KEYWORDS.has(key))
            .map(([key, value]) =>
              key === "properties" || key === "$defs"
                ? [key, Object.fromEntries(Object.entries(value).map(([name, sub]) => [name, strip(sub)]))]
                : [key, strip(value)],
            ),
        )
      : node;
const reportSchemaData = `${BANNER}export const REPORT_SCHEMA = ${JSON.stringify(strip(reportSchema))} as const;\n`;

// Every success body's schema, by operation and status, for the runtime check in api/client.ts (audit F11, #325).
const openapi = JSON.parse(readFileSync(new URL("docs/openapi.json", root), "utf8"));
const DOC_ONLY = new Set([...DOC_KEYWORDS, "examples", "example"]);
const stripDoc = (node) =>
  Array.isArray(node)
    ? node.map(stripDoc)
    : node !== null && typeof node === "object"
      ? Object.fromEntries(
          Object.entries(node)
            .filter(([key]) => !DOC_ONLY.has(key))
            .map(([key, value]) =>
              key === "properties"
                ? [key, Object.fromEntries(Object.entries(value).map(([name, sub]) => [name, stripDoc(sub)]))]
                : [key, stripDoc(value)],
            ),
        )
      : node;
const responses = {};
for (const [path, item] of Object.entries(openapi.paths)) {
  for (const [method, op] of Object.entries(item)) {
    for (const [status, response] of Object.entries(op.responses ?? {})) {
      const schema = response?.content?.["application/json"]?.schema;
      if (status.startsWith("2") && schema !== undefined)
        (responses[`${method.toUpperCase()} ${path}`] ??= {})[status] = stripDoc(schema);
    }
  }
}
const schemas = Object.fromEntries(
  Object.entries(openapi.components.schemas).map(([name, schema]) => [name, stripDoc(schema)]),
);
const responseData =
  `${BANNER}export const RESPONSE_DOCUMENT = ${JSON.stringify({ components: { schemas } })} as const;\n` +
  `export const RESPONSES: Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, unknown>>>>>> = ${JSON.stringify(responses)};\n`;

const outputs = [
  ["api/schema.generated.ts", api],
  ["api/report.generated.ts", report],
  ["api/report-schema.generated.ts", reportSchemaData],
  ["api/responses.generated.ts", responseData],
];

let stale = false;
for (const [file, text] of outputs) {
  const url = new URL(file, import.meta.url);
  if (check) {
    let committed = "";
    try {
      committed = readFileSync(url, "utf8");
    } catch {
      // missing file counts as stale
    }
    if (committed.trim() !== text.trim() && !committed.includes(text.trim())) {
      console.error(`${file} is out of date: run \`pnpm generate:api\` and commit.`);
      stale = true;
    }
  } else {
    writeFileSync(url, text);
    console.log(`wrote ${file}`);
  }
}
if (stale) process.exit(1);
if (check) console.log("generated API types match docs/openapi.json and docs/deal-analysis.schema.json");
